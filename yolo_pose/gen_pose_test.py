"""
生成本地人物姿势测试图（不需要网络下载）
- 用 PIL 绘制不同姿势的简化人体轮廓
- 测试 YOLOv8n-Pose NCNN 识别效果
"""
import os
import numpy as np
from PIL import Image, ImageDraw

os.chdir(os.path.dirname(os.path.abspath(__file__)))

W, H = 640, 480

# COCO 17 关键点骨架连接
SKELETON = [
    (0, 1), (0, 2), (1, 3), (2, 4),       # 头-眼-耳
    (5, 6),                                 # 左肩-右肩
    (5, 11), (6, 12),                       # 肩-髋
    (11, 12),                               # 左髋-右髋
    (5, 7), (7, 9),                         # 左臂
    (6, 8), (8, 10),                        # 右臂
    (11, 13), (13, 15),                     # 左腿
    (12, 14), (14, 16),                     # 右腿
]

POSE_NAMES = [
    "stand_arms_up",
    "stand_tpose",
    "sit_cross",
    "walk_pose",
    "hands_up_yoga",
]


def make_pose_image(name, keypoints, bg_color=(60, 70, 80), body_color=(220, 200, 180)):
    """
    keypoints: list of (x, y) tuples, 17 points
    顺序: 鼻子,左眼,右眼,左耳,右耳,左肩,右肩,左肘,右肘,左腕,右腕,
          左髋,右髋,左膝,右膝,左踝,右踝
    """
    img = Image.new("RGB", (W, H), bg_color)
    draw = ImageDraw.Draw(img)

    # 简化身体轮廓（椭圆连接关键点）
    for i, j in SKELETON:
        x1, y1 = keypoints[i]
        x2, y2 = keypoints[j]
        # 骨架线
        draw.line([(x1, y1), (x2, y2)], fill=body_color, width=8)
        # 关节点
        r = 6
        draw.ellipse([x1-r, y1-r, x1+r, y1+r], fill=(255, 100, 100))
        draw.ellipse([x2-r, y2-r, x2+r, y2+r], fill=(255, 100, 100))

    # 头部圆圈
    nose = keypoints[0]
    head_r = 35
    draw.ellipse([nose[0]-head_r, nose[1]-head_r-20,
                  nose[0]+head_r, nose[1]+head_r-20], fill=body_color)

    img.save(f"{name}.jpg", quality=85)
    print(f"✓ {name}.jpg")


